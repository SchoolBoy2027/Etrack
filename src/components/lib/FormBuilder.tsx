
/**
 * File: FormBuilder.tsx
 * Purpose: Reusable component for generating forms from
 *          field configuration arrays.
 *
 * Installation:
 * Run the following command from the Expo project root:
 *
 *    npx expo install @react-native-community/datetimepicker
 *
 * The DateTimePicker dependency is required for date inputs.
 * Other controls use standard React Native components.
 *
 * Usage:
 * 1. Import FormBuilder and the form field configuration.
 *
 *    import FormBuilder from "@/components/lib/FormBuilder";
 *    import Expense from "@/data/Expense";
 *
 * 2. Pass the field configuration to FormBuilder.
 *
 *    <FormBuilder inputs={Expense} onSubmit={handleSubmit} />
 *
 * Field Configuration:
 * - name: Unique field identifier.
 * - label: Text displayed for the field.
 * - type: Determines the input control.
 * - required: Indicates whether a value is required.
 *
 * Supported Input Types:
 * - text: Single-line text input.
 * - multiline: Multiline text input.
 * - currency: Currency amount input.
 * - integer: Whole-number input.
 * - date: Date selection input.
 * - select: Selection from predefined options.
 *
 * Features:
 * - Dynamically generates input controls.
 * - Supports multiple field types.
 * - Handles field values and user input.
 * - Uses FormValidator for validation.
 *
 * Notes:
 * - FormBuilder handles form rendering and input state.
 * - FormValidator handles field validation.
 * - DateUtils handles date conversion and formatting.
 * - Field definitions are maintained in separate data files.
 * - Parent components handle submitted form data.
 */

import { useState } from "react";

import {
    FlatList,
    Modal,
    Platform,
    Pressable,
    Text,
    TextInput,
    View
} from "react-native";

import DateTimePicker, {
    type DateTimePickerEvent
} from "@react-native-community/datetimepicker";

import styles from "../../constants/FormBuilderStyles";
import DateUtils from "./DateUtils";
import FormValidator from "./FormValidator";


/**
 * SelectOption
 *
 * Defines an individual option used by a selection field
 * in the FormBuilder component.
 *
 * Each option contains a display label and an associated
 * value. The label is presented to the user, while the
 * value is stored when the option is selected.
 *
 * @property label - Text displayed to the user for the option.
 *
 * @property value - String value associated with the option,
 * used for selection, storage, and validation.
 */
export type SelectOption = {
    label: string;
    value: string;
};
/**
 * FormInput
 *
 * Defines the configuration for an individual form field
 * generated by the FormBuilder component.
 *
 * Supported input types:
 *
 * - text: Single-line text input.
 * - multiline: Multiline text input.
 * - date: Native date picker.
 * - select: Selection from predefined options.
 * - currency: Numeric input for monetary amounts.
 * - integer: Whole-number input.
 *
 * @property name - Unique identifier for the field. Used as
 * the key when storing values and validation errors.
 *
 * @property label - Text displayed alongside the input field.
 *
 * @property type - Determines which input control FormBuilder
 * renders and which validation rules FormValidator applies.
 *
 * @property required - Optional flag indicating whether the
 * field must contain a value. Defaults to false.
 *
 * @property options - Optional array of SelectOption objects
 * defining the available choices for a select field.
 */
export type FormInput = {
    name: string;
    label: string;
    type: "text" | "multiline" | "date" | "select" | "currency" | "integer" | "number";
    required?: boolean;
    options?: SelectOption[];
};


/**
 * FormBuilderProps
 *
 * Defines the properties used to configure and control
 * the FormBuilder component.
 *
 * @property inputs - Array of FormInput configurations defining
 * the fields to render, their types, and validation requirements.
 *
 * @property onSubmit - Callback executed when the form passes
 * validation. Receives field values as a name/value record.
 *
 * @property initialValues - Optional initial values used to
 * populate form fields, typically when editing existing data.
 * Defaults to an empty object.
 *
 * @property submitButtonText - Optional text displayed on the
 * submit button. Defaults to "Submit".
 */
type FormBuilderProps = {
    inputs: FormInput[];
    onSubmit: (values: Record<string, string>) => void;
    initialValues?: Record<string, string>;
    submitButtonText?: string;
};

/**
 * FormBuilder
 *
 * Reusable React Native component that dynamically generates
 * forms from an array of field configurations.
 *
 * Supports the following input types:
 *
 * - text: Single-line text input.
 * - multiline: Multiline text input.
 * - currency: Numeric input with decimal keyboard.
 * - integer: Whole-number input.
 * - date: Native date picker for Android and iOS.
 * - select: Modal selection from predefined options.
 *
 * Manages field values, user input, and validation errors.
 * Uses FormValidator to validate values before submission
 * and DateUtils for date conversion and formatting.
 *
 * Displays validation errors for individual fields and
 * submits form values through the onSubmit callback only
 * when validation succeeds.
 *
 * @param inputs - Array of FormInput field configurations.
 * @param onSubmit - Callback receiving validated form values.
 * @param initialValues - Optional initial field values.
 * @param submitButtonText - Submit button label (default: "Submit").
 *
 * @returns React Native form component.
 *
 * @example
 * <FormBuilder
 *     inputs={Expense}
 *     onSubmit={handleSubmit}
 *     initialValues={initialValues}
 *     submitButtonText="Save Expense"
 * />
 */
const FormBuilder = ({
    inputs,
    onSubmit,
    initialValues = {},
    submitButtonText = "Submit"
}: FormBuilderProps) => {

    const [values, setValues] =
        useState<Record<string, string>>(initialValues);

    const [errors, setErrors] =
        useState<Record<string, string>>({});

    const [activeSelect, setActiveSelect] =
        useState<string | null>(null);

    const [activeDate, setActiveDate] =
        useState<string | null>(null);

    const [validator] = useState(() => new FormValidator());

    /**
     * handleChange()
     * Updates the value of a field and clears its validation error.
     *
     * @param name - Field identifier.
     * @param value - New field value.
     * @returns void
     */
    const handleChange = (name: string, value: string): void => {

        setValues((previous) => ({
            ...previous,
            [name]: value
        }));

        setErrors((previous) => ({
            ...previous,
            [name]: ""
        }));
    };

    /**
     * handleDateChange()
     * Processes a date selected using the native date picker.
     *
     * @param event - Date picker event.
     * @param selectedDate - Selected date.
     * @returns void
     */
    const handleDateChange = (
        event: DateTimePickerEvent,
        selectedDate?: Date
    ): void => {

        if (Platform.OS === "android") {
            setActiveDate(null);
        }

        if (event.type === "set" && selectedDate && activeDate) {
            handleChange(activeDate, DateUtils.dateToString(selectedDate));
        }
    };

    /**
     * handleSubmit()
     * Validates the form and submits values when valid.
     *
     * @returns void
     */
    const handleSubmit = (): void => {

        const valid = validator.validate(inputs, values);

        setErrors(validator.Errors);

        if (valid) {
            onSubmit(values);
        }
    };

    /**
     * renderText()
     * Renders a single-line text input.
     *
     * @param input - Field configuration.
     * @param value - Current field value.
     * @returns React input element.
     */
    const renderText = (input: FormInput, value: string) => {
        return (
            <TextInput
                style={styles.input}
                value={value}
                onChangeText={(text) => {
                    handleChange(input.name, text);
                }}
            />
        );
    };

    /**
     * renderMultiline()
     * Renders a multiline text input.
     *
     * @param input - Field configuration.
     * @param value - Current field value.
     * @returns React input element.
     */
    const renderMultiline = (input: FormInput, value: string) => {
        return (
            <TextInput
                style={[styles.input, styles.multiline]}
                value={value}
                multiline={true}
                textAlignVertical="top"
                onChangeText={(text) => {
                    handleChange(input.name, text);
                }}
            />
        );
    };

    /**
     * renderCurrency()
     * Renders a currency input.
     *
     * @param input - Field configuration.
     * @param value - Current field value.
     * @returns React input element.
     */
    const renderCurrency = (input: FormInput, value: string) => {
        return (
            <TextInput
                style={styles.input}
                value={value}
                keyboardType="decimal-pad"
                placeholder="0.00"
                onChangeText={(text) => {
                    handleChange(input.name, text);
                }}
            />
        );
    };

    /**
     * renderInteger()
     * Renders an integer input.
     *
     * @param input - Field configuration.
     * @param value - Current field value.
     * @returns React input element.
     */
    const renderInteger = (input: FormInput, value: string) => {
        return (
            <TextInput
                style={styles.input}
                value={value}
                keyboardType="number-pad"
                placeholder="0"
                onChangeText={(text) => {
                    handleChange(input.name, text);
                }}
            />
        );
    };

    /**
     * renderNumber()
     * Renders a numeric input supporting floating-point values.
     *
     * @param input - Field configuration.
     * @param value - Current field value.
     * @returns React input element.
     */
    const renderNumber = (input: FormInput, value: string) => {
        return (
            <TextInput
                style={styles.input}
                value={value}
                keyboardType="numbers-and-punctuation"
                placeholder="0.0"
                onChangeText={(text) => {
                    handleChange(input.name, text);
                }}
            />
        );
    };


    /**
     * renderDate()
     * Renders a date input with a native date picker.
     *
     * @param input - Field configuration.
     * @param value - Current field value.
     * @returns React input element.
     */
    const renderDate = (input: FormInput, value: string) => {
        return (
            <View>
                <Pressable
                    style={styles.input}
                    onPress={() => setActiveDate(input.name)}
                >
                    <Text>
                        {value || "Select a date"}
                    </Text>
                </Pressable>

                {activeDate === input.name && (
                    <View>
                        <DateTimePicker
                            value={DateUtils.stringToDate(value) ?? new Date()}
                            mode="date"
                            display="default"
                            onChange={handleDateChange}
                        />

                        {Platform.OS === "ios" && (
                            <Pressable
                                style={styles.button}
                                onPress={() => setActiveDate(null)}
                            >
                                <Text style={styles.buttonText}>
                                    Done
                                </Text>
                            </Pressable>
                        )}
                    </View>
                )}
            </View>
        );
    };

    /**
     * renderSelect()
     * Renders a selection field with a modal option list.
     *
     * @param input - Field configuration.
     * @param value - Current field value.
     * @returns React input element.
     */
    const renderSelect = (input: FormInput, value: string) => {
        return (
            <View>
                <Pressable
                    style={styles.input}
                    onPress={() => setActiveSelect(input.name)}
                >
                    <Text>
                        {input.options?.find(
                            (option) => option.value === value
                        )?.label || "Select an option"}
                    </Text>
                </Pressable>

                <Modal
                    visible={activeSelect === input.name}
                    transparent={true}
                    animationType="slide"
                    onRequestClose={() => setActiveSelect(null)}
                >
                    <View style={styles.modalContainer}>
                        <View style={styles.modalContent}>
                            <FlatList
                                data={input.options || []}
                                keyExtractor={(item) => item.value}
                                renderItem={({ item }) => (
                                    <Pressable
                                        style={styles.option}
                                        onPress={() => {
                                            handleChange(
                                                input.name,
                                                item.value
                                            );

                                            setActiveSelect(null);
                                        }}
                                    >
                                        <Text>{item.label}</Text>
                                    </Pressable>
                                )}
                            />

                            <Pressable
                                style={styles.button}
                                onPress={() => setActiveSelect(null)}
                            >
                                <Text style={styles.buttonText}>
                                    Cancel
                                </Text>
                            </Pressable>
                        </View>
                    </View>
                </Modal>
            </View>
        );
    };

    /**
     * renderInput()
     * Selects the appropriate rendering function
     * based on the field's input type.
     *
     * @param input - Field configuration.
     * @returns React input element.
     */
    const renderInput = (input: FormInput) => {
        const value = values[input.name] || "";
        let result: React.JSX.Element;          //define as a react element object

        switch (input.type) {
            case "multiline":
                result = renderMultiline(input, value);
                break;

            case "currency":
                result = renderCurrency(input, value);
                break;

            case "integer":
                result = renderInteger(input, value);
                break;

            case "date":
                result = renderDate(input, value);
                break;

            case "select":
                result = renderSelect(input, value);
                break;

            case "number":
                result = renderNumber(input, value);
                break;

            default:
                result = renderText(input, value);
                break;
        }

        return result;
    };

    return (
        <View style={styles.container}>

            {inputs.map((input) => (
                <View key={input.name} style={styles.field}>

                    <Text style={styles.label}>
                        {input.label}

                        {input.required && (
                            <Text style={styles.required}> *</Text>
                        )}
                    </Text>

                    {renderInput(input)}

                    {errors[input.name] && (
                        <Text style={styles.error}>
                            {errors[input.name]}
                        </Text>
                    )}

                </View>
            ))}
            {/* Add the submit button at the bottom */}
            <Pressable
                style={styles.button}
                onPress={handleSubmit}
            >
                <Text style={styles.buttonText}>
                    {submitButtonText}
                </Text>
            </Pressable>

        </View>
    );
};

export default FormBuilder;
